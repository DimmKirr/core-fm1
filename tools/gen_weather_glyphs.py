# ── Conversion helpers ────────────────────────────────────────────────────

def ascii_to_uint32(rows):
    """Convert 32 ASCII-art rows to list of uint32 values (MSB = leftmost)."""
    result = []
    for row in rows:
        assert len(row) == 32, f"Row length {len(row)}, expected 32: '{row}'"
        val = 0
        for i, ch in enumerate(row):
            if ch == '#':
                val |= (1 << (31 - i))
        result.append(val)
    assert len(result) == 32
    return result


def validate_glyphs():
    """Check all glyphs are 32x32."""
    for name in GLYPH_ORDER:
        rows = GLYPHS[name]
        assert len(rows) == 32, f"{name}: {len(rows)} rows, expected 32"
        for i, row in enumerate(rows):
            assert len(row) == 32, f"{name} row {i}: {len(row)} chars, expected 32"
            assert all(c in '.#' for c in row), f"{name} row {i}: invalid chars"


# ── Code generation ───────────────────────────────────────────────────────

def generate():
    validate_glyphs()

    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-3.0-only */")
    lines.append("/* AUTO-GENERATED by tools/gen_weather_glyphs.py -- DO NOT EDIT */")
    lines.append(f"/* Generated {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')} */")
    lines.append("")
    lines.append("#ifndef WEATHER_GLYPHS_H")
    lines.append("#define WEATHER_GLYPHS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")

    # Enum
    lines.append("enum {")
    for i, name in enumerate(GLYPH_ORDER):
        lines.append(f"    WTHR_G_{name} = {i},")
    lines.append(f"    WTHR_G_COUNT = {len(GLYPH_ORDER)}")
    lines.append("};")
    lines.append("")

    # Glyph data arrays
    for name in GLYPH_ORDER:
        data = ascii_to_uint32(GLYPHS[name])
        lines.append(f"static const uint32_t wthr_glyph_{name.lower()}[32] = {{")
        for i in range(0, 32, 4):
            chunk = data[i:i+4]
            lines.append("    " + ", ".join(f"0x{v:08X}" for v in chunk) + ",")
        lines.append("};")
        lines.append("")

    # Pointer array
    lines.append("static const uint32_t *const wthr_glyphs[WTHR_G_COUNT] = {")
    for name in GLYPH_ORDER:
        lines.append(f"    wthr_glyph_{name.lower()},")
    lines.append("};")
    lines.append("")

    # WMO code -> glyph index lookup
    lines.append("static int weather_glyph_for_code(uint8_t wmo_code) {")
    lines.append("    switch (wmo_code) {")
    for code, gname in WMO_GLYPH_MAP:
        lines.append(f"    case {code:3d}: return WTHR_G_{gname};")
    lines.append(f"    default:  return WTHR_G_UNKNOWN;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Draw function
    lines.append("static void weather_draw_glyph(int x, int y, int idx,")
    lines.append("                               uint16_t fg, uint16_t bg) {")
    lines.append("    if (idx < 0 || idx >= WTHR_G_COUNT) idx = WTHR_G_UNKNOWN;")
    lines.append("    const uint32_t *rows = wthr_glyphs[idx];")
    lines.append("    for (int r = 0; r < 32; r++) {")
    lines.append("        uint32_t bits = rows[r];")
    lines.append("        for (int c = 0; c < 32; c++) {")
    lines.append("            uint16_t color = (bits & (1u << (31 - c))) ? fg : bg;")
    lines.append("            cv_rect(x + c, y + r, 1, 1, color);")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("#endif /* WEATHER_GLYPHS_H */")

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(generate())
