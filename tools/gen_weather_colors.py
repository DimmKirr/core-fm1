"""Generate weather_colors.h: WMO code -> RGB565 background color mapping.

Maps ~28 WMO weather codes to 9 color categories with pleasant, modern colors
designed for readability on a 240x240 LCD with white text overlay.

Usage:
  python3 tools/gen_weather_colors.py > firmware/src/ui/felucca/weather_colors.h
"""
import sys
import datetime

# ── RGB565 helpers ──────────────────────────────────────────────────────────

def rgb_to_565(r, g, b):
    """Convert 8-bit RGB to RGB565 (5R-6G-5B)."""
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# ── Color palette ──────────────────────────────────────────────────────────
# Each category: (R, G, B) chosen for pleasant appearance on small LCD
# with white text on top.

CATEGORIES = {
    "CLEAR":    (30,  120, 220),   # bright sky blue
    "PARTLY":   (70,  140, 200),   # muted blue
    "OVERCAST": (100, 110, 125),   # steel grey
    "FOG":      (130, 135, 145),   # light grey-blue
    "DRIZZLE":  (80,  105, 140),   # slate blue
    "RAIN":     (55,  75,  120),   # deep blue-grey
    "SNOW":     (110, 130, 160),   # cool blue-grey
    "SHOWERS":  (60,  85,  130),   # medium blue
    "THUNDER":  (50,  45,  80),    # dark indigo
}

# Foreground colors for text
FG_WHITE = rgb_to_565(255, 255, 255)
FG_DIM   = rgb_to_565(200, 210, 220)

# ── WMO code mapping ──────────────────────────────────────────────────────
# (wmo_code, category_key, human_name)

WMO_CODES = [
    (0,  "CLEAR",    "CLEAR SKY"),
    (1,  "CLEAR",    "MAINLY CLEAR"),
    (2,  "PARTLY",   "PARTLY CLOUDY"),
    (3,  "OVERCAST", "OVERCAST"),
    (45, "FOG",      "FOG"),
    (48, "FOG",      "DEPOSITING RIME FOG"),
    (51, "DRIZZLE",  "LIGHT DRIZZLE"),
    (53, "DRIZZLE",  "MODERATE DRIZZLE"),
    (55, "DRIZZLE",  "DENSE DRIZZLE"),
    (56, "DRIZZLE",  "LIGHT FREEZING DRIZZLE"),
    (57, "DRIZZLE",  "DENSE FREEZING DRIZZLE"),
    (61, "RAIN",     "SLIGHT RAIN"),
    (63, "RAIN",     "MODERATE RAIN"),
    (65, "RAIN",     "HEAVY RAIN"),
    (66, "RAIN",     "LIGHT FREEZING RAIN"),
    (67, "RAIN",     "HEAVY FREEZING RAIN"),
    (71, "SNOW",     "SLIGHT SNOWFALL"),
    (73, "SNOW",     "MODERATE SNOWFALL"),
    (75, "SNOW",     "HEAVY SNOWFALL"),
    (77, "SNOW",     "SNOW GRAINS"),
    (80, "SHOWERS",  "SLIGHT RAIN SHOWERS"),
    (81, "SHOWERS",  "MODERATE RAIN SHOWERS"),
    (82, "SHOWERS",  "VIOLENT RAIN SHOWERS"),
    (85, "SNOW",     "SLIGHT SNOW SHOWERS"),
    (86, "SNOW",     "HEAVY SNOW SHOWERS"),
    (95, "THUNDER",  "THUNDERSTORM"),
    (96, "THUNDER",  "THUNDERSTORM WITH SLIGHT HAIL"),
    (99, "THUNDER",  "THUNDERSTORM WITH HEAVY HAIL"),
]


# ── Code generation ───────────────────────────────────────────────────────

def generate():
    cat_colors = {k: rgb_to_565(*v) for k, v in CATEGORIES.items()}

    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-3.0-only */")
    lines.append("/* AUTO-GENERATED by tools/gen_weather_colors.py -- DO NOT EDIT */")
    lines.append(f"/* Generated {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')} */")
    lines.append("")
    lines.append("#ifndef WEATHER_COLORS_H")
    lines.append("#define WEATHER_COLORS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")

    # Foreground color defines
    lines.append(f"#define WTHR_FG      0x{FG_WHITE:04X}  /* white */")
    lines.append(f"#define WTHR_FG_DIM  0x{FG_DIM:04X}  /* dim white */")
    lines.append("")

    # Category color defines
    lines.append("/* Background color categories (RGB565) */")
    for name, rgb in CATEGORIES.items():
        val = cat_colors[name]
        lines.append(f"#define WTHR_BG_{name:8s} 0x{val:04X}"
                     f"  /* ({rgb[0]:3d},{rgb[1]:3d},{rgb[2]:3d}) */")
    lines.append("")

    # weather_color() lookup
    lines.append("static uint16_t weather_color(uint8_t wmo_code) {")
    lines.append("    switch (wmo_code) {")
    for code, cat, _ in WMO_CODES:
        lines.append(f"    case {code:3d}: return WTHR_BG_{cat};")
    lines.append(f"    default:  return WTHR_BG_OVERCAST;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # weather_condition_name() lookup
    lines.append("static const char *weather_condition_name(uint8_t wmo_code) {")
    lines.append("    switch (wmo_code) {")
    for code, _, name in WMO_CODES:
        lines.append(f'    case {code:3d}: return "{name}";')
    lines.append('    default:  return "UNKNOWN";')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("#endif /* WEATHER_COLORS_H */")

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(generate())
