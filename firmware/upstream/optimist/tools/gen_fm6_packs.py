"""FM6's voice packs: tools/fm6_packs/pk_*.py (the voices, written in tools/fm6_packs/dx7.py) and levels.json (their level
trims, set by tools/fm6_packs_check.py) -> firmware/src/engines/fm6/eng_fm6_pk_*.h, which eng_fm6.c includes for the packs
a build has (builder items FM6_PK_*).

  tools/gen_fm6_packs.py           write the headers
  tools/gen_fm6_packs.py --check   exit 1 when a header is not what the voices make (tests/builder_test.py)
"""
import importlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "fm6_packs"))
import dx7  # noqa: E402
fm6z = importlib.import_module("fm6z")              # (the compressor beside dx7, tools/fm6_packs)

OUT = HERE.parent / "firmware/src/engines/fm6"
PACKS = ("keys", "bass", "bells", "pads", "80s")        # the builder items FM6_PK_KEYS, _BASS, _BELLS, _PADS, _80S, in this order


def load():
    levels_path = HERE / "fm6_packs" / "levels.json"
    levels = json.loads(levels_path.read_text()) if levels_path.exists() else {}
    packs = []
    for p in PACKS:
        try:
            m = importlib.import_module(f"pk_{p}")
        except ModuleNotFoundError as e:                  # (a pack not written yet: skipped, while they are being written)
            if e.name != f"pk_{p}":
                raise
            print(f"pk_{p}.py: not there, skipped", file=sys.stderr)
            continue
        vs = [dx7.with_trim(v, levels.get(p, {}).get(v.name.strip(), 0)) for v in m.VOICES]
        assert len(vs) == 16, (p, len(vs))
        assert len({v.name for v in vs}) == 16, (p, "duplicate names")
        packs.append((p, m.TITLE, vs))
    names = [v.name for _, _, vs in packs for v in vs]
    assert len(set(names)) == len(names), "a name is used twice across the packs"
    return packs


def vmem(v):
    """the voice's VMEM bytes as the firmware stores them: byte 117 (TRANSPOSE) 24, as eng_fm6_rom.h's VOICE macro always
    wrote it (a pack voice's transpose was never in the firmware: kept so, the sound unchanged)"""
    b = bytearray(dx7.pack_vmem(v))
    b[117] = 24
    return bytes(b)


def c_bytes(b, per=24, ind="    "):
    return "\n".join(ind + ", ".join(str(x) for x in b[i:i + per]) + "," for i in range(0, len(b), per))


def header(p, title, vs, dictionary):
    """the pack: its voices' VMEM compressed over the shared dictionary (fm6z.py), their offsets, their names"""
    z, at = bytearray(), [0]
    for v in vs:
        blk = fm6z.compress(vmem(v)[:fm6z.VMEM], dictionary)
        assert fm6z.decompress(blk, dictionary) == vmem(v)[:fm6z.VMEM], (p, v.name)
        z += blk
        at.append(len(z))
    P = p.upper()
    out = [f"/* SPDX-License-Identifier: GPL-3.0-only */",
           f"/* FM6 voice pack {P}: {title}. 16 voices of the project's own, programmed from scratch (nothing copied from a",
           f" * Yamaha ROM or cartridge or anyone's .syx). Generated by tools/gen_fm6_packs.py from tools/fm6_packs/pk_{p}.py: do not edit.",
           f" * Included by eng_fm6.c under FELUCCA_FM6_PK_{P}: each voice's 118 VMEM bytes compressed over FM6_PK_DICT",
           f" * (tools/fm6_packs/fm6z.py; eng_fm6.c fm6_pk_decode), {len(z)} bytes for {16 * fm6z.VMEM}; the names apart. */"]
    for v in vs:
        out.append(f"/*   {v.name.strip()}: algorithm {v.alg}, feedback {v.fb} */")
    out.append(f"static const uint8_t FM6_PK_{P}_Z[{len(z)}] = {{")
    out.append(c_bytes(z))
    out.append("};")
    out.append(f"static const uint16_t FM6_PK_{P}_AT[17] = {{{', '.join(map(str, at))}}};")
    out.append(f"static const char FM6_PK_{P}_N[16][11] = {{" + ", ".join(f'"{v.name:<10}"' for v in vs) + "};")
    return "\n".join(out) + "\n"


def dict_header(dictionary, src):
    return "\n".join([
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* FM6 voice packs: the dictionary every pack voice's compressed bytes may copy from (tools/fm6_packs/fm6z.py), the",
        f" * VMEM bytes of {src}. Generated by tools/gen_fm6_packs.py: do not edit. Included by eng_fm6.c with any pack. */",
        f"static const uint8_t FM6_PK_DICT[{len(dictionary)}] = {{",
        c_bytes(dictionary),
        "};"]) + "\n"


def main():
    check = "--check" in sys.argv
    bad = 0
    packs = load()
    allv = [(p, v) for p, _, vs in packs for v in vs]
    voices = [vmem(v)[:fm6z.VMEM] for _, v in allv]
    dictionary = fm6z.pick_dictionary(voices)
    first = voices.index(dictionary[:fm6z.VMEM])
    src = ", ".join(allv[first + i][1].name.strip() for i in range(len(dictionary) // fm6z.VMEM))
    files = [(OUT / "eng_fm6_pk_dict.h", dict_header(dictionary, src))]
    files += [(OUT / f"eng_fm6_pk_{p}.h", header(p, title, vs, dictionary)) for p, title, vs in packs]
    for path, text in files:
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"{path.name}: not what tools/fm6_packs makes")
                bad += 1
        else:
            path.write_text(text)
            print(f"{path.name}: written")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
